QString stamp(const QDateTime& value) { return value.toUTC().toString(Qt::ISODateWithMs); }
QString identity(const Group* group) { return group ? group->uuid().toString() : QString{}; }

QJsonObject custom(const CustomData* data, bool storedTimestamps = false)
{
    QJsonObject result;
    for (const auto& name : data->keys()) {
        // Only the two upstream-managed keys are excluded. User/application
        // data, including timestamps, is always compared explicitly.
        if (!data->isAutoGenerated(name)) {
            QJsonObject item{{"value", data->value(name)}};
            if (storedTimestamps) item["modified"] = stamp(data->lastModified(name));
            result[name] = item;
        }
    }
    return result;
}

QJsonObject times(const TimeInfo& value)
{
    return {{"created", stamp(value.creationTime())}, {"modified", stamp(value.lastModificationTime())},
            {"accessed", stamp(value.lastAccessTime())}, {"expiresAt", stamp(value.expiryTime())},
            {"expires", value.expires()}, {"usage", value.usageCount()}, {"location", stamp(value.locationChanged())}};
}

QJsonObject entryData(const Entry* entry)
{
    QJsonObject fields, attachments;
    for (const auto& name : entry->attributes()->keys()) {
        fields[name] = QJsonObject{{"value", entry->attributes()->value(name)},
                                  {"protected", entry->attributes()->isProtected(name)}};
    }
    for (const auto& name : entry->attachments()->keys()) {
        attachments[name] = QString::fromLatin1(entry->attachments()->value(name).toBase64());
    }
    QJsonObject totp;
    if (const auto settings = entry->totpSettings()) {
        totp = {{"key", settings->key}, {"format", int(settings->format)}, {"algorithm", int(settings->algorithm)},
                {"digits", int(settings->digits)}, {"step", int(settings->step)},
                {"encoder", QJsonObject{{"name", settings->encoder.name}, {"shortName", settings->encoder.shortName},
                    {"alphabet", settings->encoder.alphabet}, {"digits", int(settings->encoder.digits)},
                    {"step", int(settings->encoder.step)}, {"reverse", settings->encoder.reverse}}}};
    }
    QJsonArray associations, history;
    for (const auto& association : entry->autoTypeAssociations()->getAll()) {
        associations.append(QJsonArray{association.window, association.sequence});
    }
    for (const auto* item : entry->historyItems()) history.append(entryData(item));
    return {{"uuid", entry->uuid().toString()}, {"fields", fields}, {"attachments", attachments},
            {"custom", custom(entry->customData())}, {"times", times(entry->timeInfo())},
            {"icon", entry->iconNumber()}, {"customIcon", entry->iconUuid().toString()},
            {"foreground", entry->foregroundColor()}, {"background", entry->backgroundColor()},
            {"overrideUrl", entry->overrideUrl()}, {"tags", entry->tags()},
            {"autoTypeEnabled", entry->autoTypeEnabled()}, {"autoTypeObfuscation", entry->autoTypeObfuscation()},
            {"autoTypeSequence", entry->defaultAutoTypeSequence()}, {"associations", associations},
            {"qualityExcluded", entry->excludeFromReports()}, {"previousParent", entry->previousParentGroupUuid().toString()},
            {"totpSettings", totp}, {"history", history}};
}

QJsonObject variants(const QVariantMap& values)
{
    QJsonObject result;
    for (auto it = values.cbegin(); it != values.cend(); ++it) {
        QByteArray serialized;
        QDataStream stream(&serialized, QIODevice::WriteOnly);
        stream << it.value(); // Retain integer width, bool, bytes and string type.
        require(stream.status() == QDataStream::Ok, "typed variant serialization");
        result[it.key()] = QString::fromLatin1(serialized.toBase64());
    }
    return result;
}

QJsonObject snapshot(Database& db)
{
    const auto* meta = db.metadata();
    QJsonObject metadata{{"name", meta->name()}, {"description", meta->description()},
        {"generator", meta->generator()}, {"defaultUser", meta->defaultUserName()},
        {"nameChanged", stamp(meta->nameChanged())}, {"descriptionChanged", stamp(meta->descriptionChanged())},
        {"defaultUserChanged", stamp(meta->defaultUserNameChanged())}, {"settingsChanged", stamp(meta->settingsChanged())},
        {"keyChanged", stamp(meta->databaseKeyChanged())}, {"maintenanceDays", meta->maintenanceHistoryDays()},
        {"color", meta->color()}, {"keyChangeRec", meta->databaseKeyChangeRec()},
        {"keyChangeForce", meta->databaseKeyChangeForce()}, {"protectTitle", meta->protectTitle()},
        {"protectUsername", meta->protectUsername()}, {"protectPassword", meta->protectPassword()},
        {"protectUrl", meta->protectUrl()}, {"protectNotes", meta->protectNotes()},
        {"recycleEnabled", meta->recycleBinEnabled()}, {"recycleGroup", identity(meta->recycleBin())},
        {"recycleChanged", stamp(meta->recycleBinChanged())}, {"templateGroup", identity(meta->entryTemplatesGroup())},
        {"templateChanged", stamp(meta->entryTemplatesGroupChanged())},
        {"selectedGroup", identity(meta->lastSelectedGroup())}, {"visibleGroup", identity(meta->lastTopVisibleGroup())},
        {"historyItems", meta->historyMaxItems()}, {"historyBytes", meta->historyMaxSize()},
        {"custom", custom(meta->customData(), db.formatVersion() >= KeePass2::FILE_VERSION_4_1)}};
    // KDBX 3.1 does not serialize SettingsChanged. Its reader initializes a
    // fresh runtime value; it is not a stored timestamp that can be compared.
    if (db.formatVersion() < KeePass2::FILE_VERSION_4) metadata.remove("settingsChanged");
    QJsonArray icons;
    for (const auto& id : meta->customIconsOrder()) {
        const auto& icon = meta->customIcon(id);
        icons.append(QJsonObject{{"uuid", id.toString()}, {"data", QString::fromLatin1(icon.data.toBase64())},
                                 {"name", icon.name}, {"modified", stamp(icon.lastModified)}});
    }
    metadata["icons"] = icons;
    QJsonArray groups, deleted;
    QJsonObject entries, resolvedPasswords, resolvedUsernames;
    for (const auto* group : db.rootGroup()->groupsRecursive(true)) {
        QJsonArray entryOrder, childOrder;
        for (const auto* entry : group->entries()) {
            entryOrder.append(entry->uuid().toString());
            entries[entry->uuid().toString()] = entryData(entry);
            resolvedPasswords[entry->uuid().toString()] = entry->resolveMultiplePlaceholders(entry->password());
            resolvedUsernames[entry->uuid().toString()] = entry->resolveMultiplePlaceholders(entry->username());
        }
        for (const auto* child : group->children()) childOrder.append(child->uuid().toString());
        groups.append(QJsonObject{{"uuid", group->uuid().toString()}, {"parent", identity(group->parentGroup())},
            {"name", group->name()}, {"notes", group->notes()}, {"tags", group->tags()},
            {"icon", group->iconNumber()}, {"customIcon", group->iconUuid().toString()},
            {"times", times(group->timeInfo())}, {"expanded", group->isExpanded()},
            {"autoType", int(group->autoTypeEnabled())}, {"searching", int(group->searchingEnabled())},
            {"sequence", group->defaultAutoTypeSequence()}, {"previousParent", group->previousParentGroupUuid().toString()},
            {"visibleEntry", group->lastTopVisibleEntry() ? group->lastTopVisibleEntry()->uuid().toString() : QString{}},
            {"custom", custom(group->customData())}, {"entries", entryOrder}, {"children", childOrder}});
    }
    for (const auto& item : db.deletedObjects()) {
        deleted.append(QJsonObject{{"uuid", item.uuid.toString()}, {"deleted", stamp(item.deletionTime)}});
    }
    auto parameters = db.kdf()->writeParameters();
    parameters.remove(QStringLiteral("S")); // Salt is regenerated on saving.
    return {{"format", double(db.formatVersion())}, {"cipher", db.cipher().toString()},
            {"compression", int(db.compressionAlgorithm())}, {"kdf", variants(parameters)},
            {"publicData", variants(db.publicCustomData())}, {"metadata", metadata},
            {"groups", groups}, {"entries", entries}, {"resolvedPasswords", resolvedPasswords},
            {"resolvedUsernames", resolvedUsernames}, {"deleted", deleted}};
}

